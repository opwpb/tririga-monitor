import { api } from '../services/api';

export interface ChatMessage {
  role: 'user' | 'assistant';
  text: string;
  thought?: string;
}

export interface ChatExportOptions {
  title?: string;
  scope?: string;
  model?: string;
  filename?: string;
}

/**
 * Transforms an array of chat messages into clean, structured Markdown suitable
 * for direct reading or rendering into an executive Word (.docx) document.
 */
export function formatChatToMarkdown(
  messages: ChatMessage[],
  options: ChatExportOptions = {}
): string {
  const title = options.title || 'IBM TRIRIGA AI Assistant – Chat Consultation';
  const dateStr = new Date().toLocaleString('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });

  const lines: string[] = [];
  lines.push(`# ${title}`);
  lines.push(`*Exported on: ${dateStr}*`);
  if (options.scope) {
    lines.push(`*Active Scope: ${options.scope}*`);
  }
  if (options.model) {
    lines.push(`*Model: ${options.model}*`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');

  let queryIndex = 1;
  let responseIndex = 1;

  for (const msg of messages) {
    // Skip empty or trivial greeting if desired, but include if user had interactions
    if (!msg.text) continue;

    if (msg.role === 'user') {
      lines.push(`## 👤 User Query #${queryIndex++}`);
      lines.push('');
      lines.push(msg.text.trim());
      lines.push('');
      lines.push('---');
      lines.push('');
    } else {
      lines.push(`## 🤖 AI Assistant Diagnosis #${responseIndex++}`);
      lines.push('');
      lines.push(msg.text.trim());
      lines.push('');
      lines.push('---');
      lines.push('');
    }
  }

  lines.push('*Transcript generated by IBM TRIRIGA Log Analysis & Forensics AI Assistant.*');
  return lines.join('\n');
}

/**
 * Formats a single assistant response into clean Markdown with optional prompt context.
 */
export function formatSingleMessageToMarkdown(
  msg: ChatMessage,
  options: { prompt?: string; title?: string; model?: string } = {}
): string {
  const title = options.title || 'IBM TRIRIGA AI Assistant – Diagnostic Response';
  const dateStr = new Date().toLocaleString('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  const lines: string[] = [];
  lines.push(`# ${title}`);
  lines.push(`*Generated on: ${dateStr}*`);
  if (options.model) {
    lines.push(`*Model: ${options.model}*`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');

  if (options.prompt) {
    lines.push('## 👤 User Query');
    lines.push('');
    lines.push(options.prompt.trim());
    lines.push('');
    lines.push('---');
    lines.push('');
  }

  lines.push('## 🤖 AI Assistant Response');
  lines.push('');
  lines.push(msg.text.trim());
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('*Generated by IBM TRIRIGA Log Analysis & Forensics AI Assistant.*');

  return lines.join('\n');
}

/**
 * Triggers a client-side Markdown (.md) file download.
 */
export function exportChatMarkdown(
  messages: ChatMessage[],
  options: ChatExportOptions = {}
): void {
  const md = formatChatToMarkdown(messages, options);
  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const safeTitle = (options.filename || options.title || 'TRIRIGA_AI_Chat_Transcript')
    .replace(/[^a-zA-Z0-9_\-]/g, '_');
  a.download = `${safeTitle}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Calls backend Word exporter to generate and download a styled .docx file.
 */
export async function exportChatDocx(
  messages: ChatMessage[],
  options: ChatExportOptions = {}
): Promise<void> {
  const title = options.title || 'IBM TRIRIGA AI Assistant – Chat Consultation';
  const md = formatChatToMarkdown(messages, options);
  await api.exportDocx(title, md);
}

